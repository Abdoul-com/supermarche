CREATE OR REPLACE FUNCTION public.current_user_id()
RETURNS bigint
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT u.id
  FROM public.users AS u
  WHERE u.auth_user_id = auth.uid()
    AND lower(u.statut) = 'actif'
  LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.user_has_roles(role_names text[])
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users AS u
    JOIN public.roles AS r ON r.id = u.role_id
    WHERE u.auth_user_id = auth.uid()
      AND lower(u.statut) = 'actif'
      AND r.nom = ANY (role_names)
  );
$$;

REVOKE ALL ON FUNCTION public.current_user_id() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.user_has_roles(text[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.current_user_id() TO authenticated;
GRANT EXECUTE ON FUNCTION public.user_has_roles(text[]) TO authenticated;

