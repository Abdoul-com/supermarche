CREATE OR REPLACE FUNCTION public.guard_cashier_product_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF auth.uid() IS NOT NULL
    AND NOT public.user_has_roles(ARRAY['Administrateur', 'Gérant', 'Gestionnaire de stock'])
    AND (to_jsonb(NEW) - 'stock_actuel' - 'updated_at') IS DISTINCT FROM
        (to_jsonb(OLD) - 'stock_actuel' - 'updated_at') THEN
    RAISE EXCEPTION 'Le rôle Caissier peut uniquement modifier le stock.';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER products_guard_cashier_update
  BEFORE UPDATE ON public.products
  FOR EACH ROW EXECUTE FUNCTION public.guard_cashier_product_update();

CREATE OR REPLACE FUNCTION public.guard_admin_role_assignment()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  assigned_role text;
BEGIN
  IF auth.uid() IS NOT NULL
    AND NOT public.user_has_roles(ARRAY['Administrateur'])
    AND NEW.role_id IS NOT NULL THEN
    SELECT r.nom INTO assigned_role FROM public.roles AS r WHERE r.id = NEW.role_id;
    IF assigned_role = 'Administrateur' THEN
      RAISE EXCEPTION 'Seul un administrateur peut attribuer le rôle Administrateur.';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER users_guard_admin_role_assignment
  BEFORE INSERT OR UPDATE OF role_id ON public.users
  FOR EACH ROW EXECUTE FUNCTION public.guard_admin_role_assignment();

